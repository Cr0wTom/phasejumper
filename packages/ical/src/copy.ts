export const FLIGHT_COLOR = "gray";

export function isExportedKind(kind: BlockKind): kind is ExportedKind {
  return EXPORTABLE[kind];
}

/** Caffeine stop and the melatonin window are 5-minute events at their start. */
export function isMarker(kind: ExportedKind): boolean {
  return MARKER[kind];
}

export function eventSummary(kind: ExportedKind, minutes: number): string {
  return `${SUMMARY[kind]} (${minutes} min)`;
}

export function eventDescription(
  reason: string,
  grade: EvidenceGrade,
  engineVersion: string,
): string {
  return `${reason}\n\nEvidence grade ${grade}\nGenerated by PhaseJumper engine v${engineVersion}`;
}

export function alarmMinutes(kind: ExportedKind): number | null {
  return ALARM_MINUTES[kind];
}

export function alarmText(): string {
  return "An alert in your calendar.";
}

export function eventColor(kind: ExportedKind): string {
  return COLOR[kind];
}

export function flightSummary(
  from: string,
  to: string,
  flightNumber: string | undefined,
): string {
  const route = `Flight ${from} to ${to}`;
  if (flightNumber === undefined || flightNumber.length === 0) return route;
  return `${route} (${flightNumber})`;
}

export function calendarName(origin: string, destination: string): string {
  return `PhaseJumper — ${origin} → ${destination}`;
}
